def text_width(s, scale=3):
    """Pixel width of string s at the given scale (no drawing)."""
    if not s:
        return 0
    return len(s) * 6 * scale - scale


def draw_text(cv, x, y, s, color, scale=3):
    """Draw s with the top-left of the first glyph at (x, y).

    Each glyph pixel becomes a filled scale-by-scale square.
    Returns the total width drawn in pixels.
    """
    for ch in s:
        glyph = GLYPHS.get(ch)
        if glyph is None:
            if ch != ' ' and '?' in GLYPHS:
                glyph = GLYPHS['?']
        if glyph is not None:
            for gy, row in enumerate(glyph):
                for gx, bit in enumerate(row):
                    if bit == '#':
                        cv.rect(x + gx * scale, y + gy * scale,
                                scale, scale, color)
        x += 6 * scale
    return text_width(s, scale)


def draw_text_center(cv, cx, y, s, color, scale=3):
    """Draw s horizontally centred on cx, top at y. Returns the width."""
    w = text_width(s, scale)
    draw_text(cv, cx - w // 2, y, s, color, scale)
    return w


def draw_text_right(cv, xr, y, s, color, scale=3):
    """Draw s so its right edge is at xr, top at y. Returns the width."""
    w = text_width(s, scale)
    draw_text(cv, xr - w, y, s, color, scale)
    return w
